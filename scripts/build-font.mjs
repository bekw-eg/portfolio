function glyphFor(ch, rows) {
  const path = new opentype.Path();
  const width = Math.max(...rows.map((r) => r.length));
  rows.forEach((row, r) => {
    // merge horizontal runs into one rectangle each
    let c = 0;
    while (c < row.length) {
      if (row[c] !== '#') { c++; continue; }
      const start = c;
      while (c < row.length && row[c] === '#') c++;
      const x0 = start * P, x1 = c * P;
      const y0 = (6 - r) * P, y1 = (7 - r) * P; // row 6 sits on the baseline
      path.moveTo(x0, y0); path.lineTo(x0, y1); path.lineTo(x1, y1); path.lineTo(x1, y0); path.close();
    }
  });
  return new opentype.Glyph({
    name: `u${ch.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')}`,
    unicode: ch.codePointAt(0),
    advanceWidth: (width + 1) * P,
    path,
  });
}

const glyphs = [
  new opentype.Glyph({ name: '.notdef', unicode: 0, advanceWidth: 6 * P, path: new opentype.Path() }),
  new opentype.Glyph({ name: 'space', unicode: 32, advanceWidth: 4 * P, path: new opentype.Path() }),
  new opentype.Glyph({ name: 'nbsp', unicode: 160, advanceWidth: 4 * P, path: new opentype.Path() }),
  ...Object.entries(G).map(([ch, rows]) => glyphFor(ch, rows)),
];

const font = new opentype.Font({
  familyName: 'Blockcraft',
  styleName: 'Regular',
  unitsPerEm: 8 * P,
  ascender: 8 * P,
  descender: -2 * P,
  designer: 'Berdibek Egeubay',
  description: 'Original pixel font in a blocky game-UI style.',
  glyphs,
});

const outPath = fileURLToPath(OUT);
